import type { FocusStack } from '../focus/types.ts';
import type { InvariantResult } from '../invariants/engine.ts';

/**
 * The committed, human-readable map.
 *
 * JSON is what the tool reads; this is what a person reviewing a pull request reads. If the
 * architecture changed, the diff on this file says so in one screen — which is the only way
 * a structural change gets noticed during review rather than six months later.
 *
 * Deliberately contains no counts that churn without meaning and no timestamps.
 */
export function toArchitectureDoc(
  stack: FocusStack,
  invariants: InvariantResult[],
  opts: { repo?: string } = {},
): string {
  const l3 = stack.levels.find((l) => l.level === 3);
  const named = (l3?.nodes ?? []).filter((n) => n.purpose);
  const unnamed = (l3?.nodes ?? []).filter((n) => !n.purpose);
  const lines: string[] = [];

  lines.push('# Architecture');
  lines.push('');
  lines.push(
    'Generated by `daylight export`. The JSON beside it is what the tool reads; this is what a',
    'reviewer reads. Do not edit by hand — edit the target or the invariants and re-export.',
  );
  lines.push('');
  lines.push(`**L3 status: ${stack.l3Status}**` + (opts.repo ? ` · \`${opts.repo}\`` : ''));
  lines.push('');

  if (!named.length) {
    lines.push('No subsystem has an agent-written purpose yet, so the levels below are path');
    lines.push('grouping — how the code is filed, not what it is for. Run a focus pass.');
    lines.push('');
  }

  lines.push('## Subsystems');
  lines.push('');
  lines.push('| Subsystem | Files | Purpose |');
  lines.push('| --- | --- | --- |');
  for (const n of [...named].sort((a, b) => b.fileCount - a.fileCount)) {
    lines.push(`| **${n.label}** | ${n.fileCount} | ${n.purpose?.replace(/\|/g, '\\|') ?? ''} |`);
  }
  for (const n of [...unnamed].sort((a, b) => b.fileCount - a.fileCount)) {
    lines.push(`| ${n.label} | ${n.fileCount} | _unfocused — path grouping_ |`);
  }
  lines.push('');

  // Mermaid so the shape renders in a PR without anyone installing anything.
  if (l3) {
    const id = (s: string) => 'n_' + s.replace(/[^A-Za-z0-9]/g, '_');
    lines.push('```mermaid');
    lines.push('flowchart LR');
    for (const n of l3.nodes) {
      lines.push(`    ${id(n.id)}["${n.label.replace(/"/g, "'")}<br/>${n.fileCount} files"]`);
    }
    lines.push('');
    for (const e of [...l3.edges].sort((a, b) => b.weight - a.weight).slice(0, 40)) {
      lines.push(`    ${id(e.from)} -->|${e.weight}| ${id(e.to)}`);
    }
    lines.push('```');
    lines.push('');
  }

  lines.push('## Invariants');
  lines.push('');
  if (!invariants.length) {
    lines.push('None declared. L3 reports `UNPROVEN` rather than claiming to be verified.');
  } else {
    for (const r of invariants) {
      lines.push(`- ${r.status === 'green' ? '✅' : '❌'} **${r.id}** — ${r.prose}`);
      if (r.status === 'red') lines.push(`  - ${r.measured}`);
    }
  }
  lines.push('');

  const elided = l3?.elided ?? [];
  if (elided.length) {
    lines.push('## What was elided to get here');
    lines.push('');
    lines.push('Every collapse is reversible and attributable; a focused map that cannot be');
    lines.push('expanded back to its members is indistinguishable from a lie.');
    lines.push('');
    for (const e of elided) lines.push(`- ${e.members} member(s) — ${e.reason}`);
    lines.push('');
  }

  return lines.join('\n');
}
